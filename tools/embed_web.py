#!/usr/bin/env python3
"""Embed the offline UI as deterministic gzip resources. No third-party packages."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path


ASSETS = (
    ("index.html", "text/html; charset=utf-8"),
    ("style.css", "text/css; charset=utf-8"),
    ("core.mjs", "text/javascript; charset=utf-8"),
    ("app.mjs", "text/javascript; charset=utf-8"),
    ("i18n.mjs", "text/javascript; charset=utf-8"),
    ("messages.mjs", "text/javascript; charset=utf-8"),
    ("demo.mjs", "text/javascript; charset=utf-8"),
)

HEADER = """/* Generated by tools/embed_web.py; do not edit. */
#pragma once
#include <stddef.h>
#include <stdint.h>

typedef struct {
    const char *uri;
    const char *content_type;
    const uint8_t *data;
    size_t size;
    const char *etag;
} web_asset_t;

/* Resources are gzip encoded. Set Content-Encoding: gzip on every response. */
const web_asset_t *web_asset_find(const char *uri);
"""


def generate(web_dir: Path, output_dir: Path) -> list[dict]:
    output_dir.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by tools/embed_web.py; do not edit. */',
             '#include "web_assets.h"', '#include <string.h>', '']
    entries = []
    manifest = []
    for index, (name, content_type) in enumerate(ASSETS):
        raw = (web_dir / name).read_bytes()
        encoded = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
        encoded[9] = 255  # Do not vary the gzip OS byte between build hosts.
        data = bytes(encoded)
        digest = hashlib.sha256(data).hexdigest()
        identifier = f"asset_{index}"
        lines.append(f"static const uint8_t {identifier}[] = {{")
        for offset in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
        lines.extend(["};", ""])
        entries.append(f'    {{"/{name}", "{content_type}", {identifier}, sizeof({identifier}), "\\\"{digest[:24]}\\\""}},')
        manifest.append({"uri": "/" + name, "content_type": content_type,
                         "raw_bytes": len(raw), "gzip_bytes": len(data), "sha256": digest})
    lines.extend(["static const web_asset_t assets[] = {", *entries, "};", "",
                  "const web_asset_t *web_asset_find(const char *uri)", "{",
                  "    if (!uri) return NULL;",
                  "    size_t length = strcspn(uri, \"?\");",
                  "    if (length == 1 && uri[0] == '/') return &assets[0];",
                  "    for (size_t i = 0; i < sizeof(assets) / sizeof(assets[0]); ++i) {",
                  "        if (strlen(assets[i].uri) == length && strncmp(uri, assets[i].uri, length) == 0)",
                  "            return &assets[i];", "    }", "    return NULL;", "}", ""])
    (output_dir / "web_assets.h").write_text(HEADER, encoding="utf-8", newline="\n")
    (output_dir / "web_assets.c").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    (output_dir / "web_assets.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--web-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    manifest = generate(args.web_dir, args.output_dir)
    print(f"Embedded {len(manifest)} offline assets: "
          f"{sum(item['raw_bytes'] for item in manifest)} raw bytes -> "
          f"{sum(item['gzip_bytes'] for item in manifest)} gzip bytes")


if __name__ == "__main__":
    main()
